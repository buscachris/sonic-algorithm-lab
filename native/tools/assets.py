#!/usr/bin/env python3
"""Extract native SAGE/Sonic artwork and arrange existing blocks into flat rooms.

No artwork is drawn by this tool. The native dialogue font's background
index is made transparent; its lettering and outline pixels are unchanged.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
import struct

from template import TemplateError, load_template

ROOT = Path(__file__).resolve().parents[2]
CHARSET = ' ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-=>$<?'
OUT = ROOT / 'native/assets'


def text(label, s, width=None):
    if width is not None:
        assert len(s) <= width, (label, len(s))
        s = s.ljust(width)
    return label + ':\n        dc.b ' + ','.join(str(CHARSET.index(c)) for c in s) + '\n'


def piece(y, size, tile, x):
    return [y & 255, size, tile >> 8, tile & 255, x & 255]


def maps(label, frames):
    s = '        even\n' + label + ':\n'
    s += '        dc.w ' + ','.join(f'.f{i}-{label}' for i in range(len(frames))) + '\n'
    for i, pieces in enumerate(frames):
        s += f'.f{i}: dc.b {len(pieces)}\n'
        for p in pieces:
            s += '        dc.b ' + ','.join(map(str, p)) + '\n'
    return s


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--template', type=Path, help='Exact SAGE parent ROM; overrides SONIC_LAB_TEMPLATE')
    args = parser.parse_args()
    try:
        _, parent = load_template(args.template)
    except TemplateError as error:
        parser.error(str(error))
    if not __debug__:
        parser.error('Asset checks require Python without -O or PYTHONOPTIMIZE.')
    OUT.mkdir(parents=True, exist_ok=True)
    provenance = []

    def extract(name, address, size):
        data = parent[address:address+size]
        assert len(data) == size
        provenance.append(dict(asset=name, address=hex(address), bytes=size,
                               sha256=hashlib.sha256(data).hexdigest()))
        return data

    font = extract('Original SAGE dialogue font', 0xE9B90, 116*32)
    indices = [ord(c)-12 for c in CHARSET]
    assert len(indices) == len(CHARSET)
    tiles = bytearray(b''.join(font[i*32:(i+1)*32] for i in indices))
    # Native letters already have a black outline. Remove only their solid
    # dialogue-window background so they work over each zone's own graphics.
    tiles = bytearray(((0 if b >> 4 == 12 else b >> 4) << 4) |
                      (0 if b & 15 == 12 else b & 15) for b in tiles)
    switch_tile = len(tiles)//32
    tiles.extend(bytes(8*32))  # Native NemDec fills this from ROM $4A02C.
    ring_tile = len(tiles)//32
    tiles.extend(extract('Original giant ring face', 0xD725E, 44*32))
    monitor_tile = len(tiles)//32
    tiles.extend(bytes(16*32))  # Copy native D200-D3FF before drawing the HUD.
    assert len(tiles) <= 4096
    (OUT/'tiles.bin').write_bytes(tiles)

    s = '; Generated by native/tools/assets.py. Native graphics only.\n'
    s += f'FontCount equ {len(CHARSET)}\nSwitchTile equ {switch_tile}\nRingTile equ {ring_tile}\n'
    s += f'MonitorTile equ {monitor_tile} ; native body copied out of the window plane\n'
    s += 'TokenTile equ $7B2-LabTile ; native collectible ring at VRAM F640\n'
    s += f'DigitZero equ {CHARSET.index("0")}\nLetterA equ {CHARSET.index("A")}\n'
    for name, char in [('Dash', '-'), ('Equals', '='), ('Greater', '>'), ('Less', '<'), ('Question', '?')]:
        s += f'Glyph{name} equ {CHARSET.index(char)}\n'
    switch_frames = []
    for label in ('BUBBLE', 'INSERT', 'SEARCH', 'BFS', 'CPU', 'MEMORY',
                  'SELECT', 'ODD EVEN', 'MERGE', 'QUICK', 'HEAP', 'LINEAR',
                  'STEP', 'RUN', 'RESET', 'INPUT', 'PAUSE'):
        for pressed in (0, 1):
            ps = [piece(-11, 5, switch_tile + pressed*4, -16),
                  piece(-11, 5, 0x800 | (switch_tile + pressed*4), 0)]
            for i, c in enumerate(label):
                ps.append(piece(-24, 0, CHARSET.index(c), -len(label)*4 + i*8))
            switch_frames.append(ps)
    s += maps('SwitchMaps', switch_frames)
    ring_frames = []
    for label in ('BUBBLE', 'INSERTION', 'SEARCH', 'BFS', 'PRIORITY', 'FIRST FIT',
                  'SELECTION', 'ODD EVEN', 'MERGE', 'QUICK', 'HEAP', 'LINEAR', 'HUB'):
        ps = []
        for i in range(10):
            y, size, tile, x = struct.unpack_from('>bBHb', parent, 0xD8AB+i*5)
            ps.append(piece(y, size, 0x2000 | (ring_tile + tile), x))
        for i, c in enumerate(label):
            ps.append(piece(-44, 0, CHARSET.index(c), -len(label)*4 + i*8))
        ring_frames.append(ps)
    s += maps('RingMaps', ring_frames)

    # Copy all original chunks used by the backgrounds, then append two new
    # foreground arrangements made only from each zone's native 16px blocks.
    for name, base, count in (('ghz', 0x59200, 63), ('mz', 0x72F4C, 67),
                              ('lz', 0x65768, 57), ('slz', 0x81B90, 50),
                              ('syz', 0x90434, 65), ('sbz', 0x9E2B0, 67)):
        bank = bytearray(extract(name.upper()+' original background chunks', base, count*512))
        floor = [0]*256
        if name == 'ghz':
            # Preserve one original palm from GHZ's opening chunk.
            opening = struct.unpack_from('>256H', parent, base+44*512)
            for y in range(11):
                for x in range(11, 16):
                    floor[y*16+x] = opening[y*16+x]
            floor[11*16:12*16] = [0x0803]*16
            floor[11*16+13] = opening[11*16+13]
            floor[12*16:13*16] = [0x6813]*16
            floor[13*16:14*16] = [0x6823]*16
            floor[14*16:] = [0x6001]*32
            fill = [0x6001]*256
        elif name == 'mz':
            floor[7*16:8*16] = [0x0804]*16
            floor[8*16:9*16] = [0x6008, 0x6009, 0x600A, 0x600B]*4
            floor[9*16:10*16] = [0x600C, 0x600D, 0x600E, 0x600F]*4
            fill = ([0x616A, 0x616B]*8 + [0x616C, 0x616D]*8)*8
            floor[10*16:] = fill[:6*16]
        else:
            # These are full-height collision blocks from each original zone.
            # Water, slides, enemies and machinery are outside the lab rooms.
            top, under, solid = {
                'lz': ([0x600A, 0x600B]*8, [0x600C, 0x600D]*8, 0x60AD),
                'slz': ([0x613F, 0x6001]*8, [0x6006]*16, 0x6006),
                'syz': ([0x6182]*16, [0x6183]*16, 0x610A),
                'sbz': ([0x6005]*16, [0x60EE]*16, 0x60EE),
            }[name]
            floor[8*16:9*16] = top
            floor[9*16:10*16] = under
            floor[10*16:] = [solid]*96
            fill = [solid]*256
        bank.extend(struct.pack('>512H', *(floor+fill)))
        (OUT/(name+'-chunks.bin')).write_bytes(bank)
        s += f'{name.upper()}FloorChunk equ {count+1}\n{name.upper()}FillChunk equ {count+2}\n'

    # Field commands are generated with the text so HUD columns cannot drift.
    def row(label, number, pattern):
        nonlocal s
        fields = []
        result = ''
        start = 0
        for match in re.finditer(r'\{(\w+):(\d+)\}', pattern):
            result += pattern[start:match.start()]
            command = 0x50000003 + ((number*0x80+len(result)*2) << 16)
            fields.append(f'{label}{match[1]} equ ${command:08X}\n')
            result += ' '*int(match[2])
            start = match.end()
        result += pattern[start:]
        s += ''.join(fields) + text(label, result, 40)

    s += 'HubRows:\n'
    row('HubTitle', 0, ' SONIC ALGORITHM LAB'.ljust(35)+'{Count:2}-12')
    row('HubNames1', 1, ' 1 BUBBLE  2 INSERT  3 BINARY  4 BFS')
    row('HubNames2', 2, ' 5 CPU  6 MEMORY  7 SELECT  8 ODD EVEN')
    row('HubDirections', 3, ' 9 MERGE  10 QUICK  11 HEAP  12 LINEAR')
    row('HubInstructions', 4, ' LAND ON A SWITCH - JUMP INTO ITS RING')
    row('HubControls', 5, ' WALK RIGHT - ABC JUMP - START PAUSE')
    s += 'StageTitles:\n'
    for title in (' BUBBLE SORT - GREEN HILL ZONE', ' INSERTION SORT - MARBLE ZONE',
                  ' BINARY SEARCH - SPRING YARD ZONE', ' BREADTH FIRST SEARCH - LABYRINTH ZONE',
                  ' PRIORITY SCHEDULING - STAR LIGHT ZONE', ' FIRST FIT MEMORY - SCRAP BRAIN ZONE',
                  ' SELECTION SORT - GREEN HILL ZONE', ' ODD EVEN SORT - MARBLE ZONE',
                  ' MERGE SORT - SPRING YARD ZONE', ' QUICKSORT - LABYRINTH ZONE',
                  ' HEAP SORT - STAR LIGHT ZONE', ' LINEAR SEARCH - SCRAP BRAIN ZONE'):
        s += text('StageTitle'+str(len(s)), title, 40)
    s += 'StageRules:\n'
    for rule in (' LARGEST BUBBLES RIGHT AFTER EACH PASS', ' INSERT EACH KEY INTO THE SORTED LEFT',
                 ' SORTED VALUES - TEST THE MIDDLE', ' A TO H - FIFO - NUMBERS ARE DISTANCES',
                 ' ALL ARRIVE AT 0 - ONE STEP IS ONE TICK', ' SCAN FROM A - SPLIT FIRST FITTING BLOCK',
                 ' SELECT THE MINIMUM - EXCHANGE AT FRONT',
                 ' ALTERNATE EVEN AND ODD ADJACENT PAIRS',
                 ' MERGE RUNS 1 THEN 2 THEN 4 - TIES LEFT',
                 ' LAST VALUE IS PIVOT - SMALL VALUES LEFT',
                 ' BUILD MAX HEAP - MOVE ITS ROOT TO END',
                 ' SCAN LEFT TO RIGHT - FIRST MATCH STOPS'):
        s += text('StageRule'+str(len(s)), rule, 40)

    rows = {
        'RepeatsRule': ' EQUAL VALUES KEEP THEIR LETTER ORDER',
        'ReadyMessage': ' STEP ONE PAIR   RUN AUTO   INPUT CHANGE',
        'RunningMessage': ' RUNNING - LAND ON RUN TO PAUSE',
        'PausedMessage': ' PAUSED - STEP ONE PAIR OR RUN TO RESUME',
        'SwapMessage': '     VS    SWAP THE MARKED MONITORS',
        'KeepMessage': '     VS    KEEP THEIR ORDER',
        'DoneMessage': ' SORTED - WALK RIGHT TO THE HUB RING',
        'HubReturnMessage': ' JUMP INTO THE RING TO RETURN TO THE HUB',
        'SortIDs': ' A-H KEEP ORIGINAL ORDER OF EQUAL VALUES',
        'UnstableIDs': ' A-H LABEL ORIGINAL ITEMS - MAY REORDER',
        'SelectionMessage': '     VS    KEEP THE SMALLER AS MINIMUM',
        'HeapMessage': '     VS    KEEP THE LARGER AS HEAP ROOT',
        'QuickMessage': '     <=    PIVOT - SMALL VALUES GO LEFT',
        'PivotMessage': '     VS    PLACE PIVOT AT ITS FINAL SLOT',
        'LinearReady': ' STEP ONE VALUE - RUN SCANS TO THE RIGHT',
        'LinearNext': ' VALUE NOT EQUAL - ADVANCE ONE POSITION',
        'ResetHelp': ' RESET SAME INPUT - INPUT NEXT EXAMPLE',
        'BlankRow': '',
        'BinaryLess': ' VALUE < TARGET - DISCARD LEFT HALF',
        'BinaryGreater': ' VALUE > TARGET - DISCARD RIGHT HALF',
        'BinaryEqual': ' VALUE = TARGET - MATCH FOUND',
        'BinaryAbsent': ' NOT FOUND - NO CANDIDATES REMAIN',
        'BFSReady': ' STEP A NODE OR EDGE - RUN FINDS A PATH',
        'BFSDequeue': ' DEQUEUE    - EXPLORE ITS NEIGHBORS',
        'BFSSeen': ' EDGE   >   - ALREADY DISCOVERED',
        'BFSDiscover': ' EDGE   >   - DISCOVER AND SET PARENT',
        'BFSAbsent': ' NO PATH - THE FIFO QUEUE IS EMPTY',
        'PriorityReady': ' LOW PRIORITY FIRST - BURST BREAKS TIES',
        'PriorityDone': ' FINISHED - MONITORS SHOW REMAINING TIME',
        'FirstFitReady': ' MONITORS A-E SHOW FREE SPACE IN UNITS',
        'FirstFitDone': ' DONE - A DASH MEANS REQUEST DID NOT FIT',
    }
    for name, line in rows.items():
        s += text(name, line, 40)

    row('Counters', 2, ' CMP {Compare:2}  SWAP {Swap:2}  INPUT {Input:8}')
    row('BinaryCounters', 2, ' TARGET {Target:1}  TESTS {Tests:2}  INPUT {Input:8}')
    row('BinaryBounds', 3, ' LOW {Low:1}  HIGH {High:1}  MID {Mid:1}  VALUE {Value:1}')
    row('BinaryCandidates', 4, ' CANDIDATES {List:8}  FOUND {Found:1}')
    row('BFSCounters', 2, ' SEEN {Seen:1}  FIFO {Queue:8}  INPUT {Input:8}')
    row('BFSPathRow', 3, ' SHORTEST PATH {Path:15}  EDGES {Distance:1}')
    row('PriorityCounters', 2, ' TIME {Time:2}  WAIT SUM {Wait:2}  INPUT {Input:8}')
    row('PriorityTick', 3, ' JOB {Job:1}  BURST LEFT {Burst:1}  NONPREEMPTIVE')
    row('PriorityOrder', 4, ' PRIORITIES {Priorities:11}  ORDER {Order:4}')
    row('PriorityWaits', 5, ' WAIT A {A:2}  B {B:2}  C {C:2}  D {D:2} - SUM ABOVE')
    row('FitCounters', 2, ' CHECKS {Checks:2}  PLACED {Placed:1}  INPUT {Input:8}')
    row('FitScan', 3, ' REQUEST {Request:1} NEEDS {Need:1}  BLOCK {Block:1} HAS {Free:1}')
    row('FitRequests', 4, ' REQUEST UNITS {Requests:15}')
    row('FitResults', 5, ' BLOCK FOR {Results:15}  ? PENDING')
    row('SelectionIndices', 4, ' FRONT {Front:1}  MIN INDEX {Min:1}  SCAN INDEX {Scan:1}')
    row('OddEvenIndices', 4, ' ROUND {Round:1}  PAIRS START AT INDEX {Start:1}')
    row('QuickIndices', 4, ' RANGE {Low:1}-{High:1}  PIVOT SLOT {Slot:1}  STACK {Stack:1}')
    row('HeapIndices', 4, ' HEAP SIZE {Size:1}  ROOT {Root:1}  SORTED {Sorted:1}')
    row('MergeCounters', 2, ' CMP {Compare:2}  WRITE {Writes:2}  INPUT {Input:8}')
    row('MergeStep', 3, ' WIDTH {Width:1}  COPY INDEX {Source:1} TO INDEX {Write:1}')
    row('MergeBuffer', 4, ' BUFFER {Values:8}  IDS {IDs:8}')
    row('LinearCursor', 3, ' INDEX {Index:1}  VALUE {Value:1}  TARGET {Target:1}')
    row('LinearResult', 4, ' FOUND INDEX {Found:1} - FIRST MATCH STOPS')
    s += 'InputNames:\n'
    for names in (('MIXED', 'REVERSE', 'NEARLY', 'SORTED', 'REPEATS'),
                  ('MIXED', 'REVERSE', 'NEARLY', 'SORTED', 'REPEATS'),
                  ('MIDDLE', 'FIRST', 'LAST', 'ABSENT', 'REPEATS'),
                  ('TREE', 'CYCLE', 'BLOCKED', 'SHORTCUT', 'DIAMOND'),
                  ('ORIGINAL', 'REVERSE', 'TIES', 'STABLE', 'LONG JOB'),
                  ('MIXED', 'EXACT', 'REUSE', 'FAILURES', 'ZEROS'),
                  *(('MIXED', 'REVERSE', 'NEARLY', 'SORTED', 'REPEATS'),)*5,
                  ('MIXED', 'FIRST', 'LAST', 'ABSENT', 'REPEATS')):
        for name in names:
            s += '        dc.b '+','.join(str(CHARSET.index(c)) for c in name.ljust(8))+'\n'
    s += '        even\n'
    (OUT/'assets.inc').write_text(s)
    (OUT/'provenance.json').write_text(json.dumps(dict(
        pixel_source='Native graphics from the exact SAGE 2010 parent',
        extracted=provenance, font_tile_order=indices,
        font_background='Native index 12 made transparent (0); lettering and outlines unchanged',
        runtime_native_art=dict(monitor='0x515A2 -> VRAM 0xD200; first 16 native tiles copied into lab art before the HUD',
                                switch='0x4A02C -> reserved lab tiles via native NemDec',
                                ring_marker='0x5493E -> VRAM 0xF640 (native collectible ring)'),
        terrain='Original zone block mappings, art, palettes and collision indices; only chunk arrangements change',
        backgrounds='Original GHZ, MZ, SYZ, LZ, SLZ and SBZ layouts, chunks, scrolling and palette animation'), indent=2)+'\n')


if __name__ == '__main__':
    main()
